      <div id="tamborMina">
        <h2 class="text-h4 pa-4">Tambor de Mina</h2>

        <p class="pa-4">
          Tambor de Mina é uma tradição religiosa afro-brasileira, praticada
          principalmente nos estados brasileiros do Maranhão, Piauí, Pará e na
          floresta amazônica. O termo "Tambor" refere-se à importância do
          elemento rítmico para o culto, e "Mina" deriva do nome São Jorge da
          Mina (Elmina Castle), referindo-se a uma designação dada a escravos
          africanos.
        </p>

        <h2 class="text-h5 pa-4">História no Brasil</h2>

        <p class="pa-4">
          A escravidão no Maranhão concentrou-se no Vale do Itapecuru, na
          Baixada Maranhense e em São Luís. As plantações de algodão e
          cana-de-açúcar contribuíram fortemente para o desenvolvimento de
          cidades maiores. Casas coloniais foram construídas com trabalho
          escravo, com seu design único influenciado pela harmonia, beleza e
          coreografia de canções originárias da África antiga. Os dois
          principais modelos de Tambor de Mina no Maranhão são Jeje e Nagô. O
          primeiro parece ser o mais antigo e se estabeleceu em torno da Casa
          Grande das Minas Jeje, mais conhecida como Casa das Minas (Querebentã
          de Tói Zomadônu), o templo mais antigo, fundado em São Luís na década
          de 1840. O outro, quase contemporâneo, se estabeleceu em torno da Casa
          de Nagô.
        </p>

        <h2 class="text-h5 pa-4">Principais Voduns e Entidades Cultuados</h2>

        <p class="pa-4">
          O Tambor de Mina cultua voduns, orixás e entidades (também chamadas
          Encantados, espíritos de pessoas) que são chamadas de gentis (se são
          reis, príncipes e nobres europeus, como o Rei Sebastião de Portugal)
          ou caboclos (se são de origem nativa, ouTurcos de origem moura, ou
          povos indígenas). Os voduns, deuses do povo fon ou jeje, são forças da
          natureza e ancestrais humanos deificados. Alguns voduns jovens
          chamados toquém ou toquenos cumprem a função de guias, mensageiros,
          ajudantes dos outros voduns. Tobóssis são divindades femininas
          infantis, consideradas filhas de voduns. Os voduns são agrupados em 5
          famílias: Davice, Quevioçô, Dambirá, Aladanu e Savaluno. Os encantados
          são entidades de pessoas que não morreram, mas desapareceram
          misteriosamente, tornando-se invisíveis ou transformando-se em animais
          ou plantas, vivendo em um reino mágico chamado Encantaria. Os
          encantados são organizados em famílias no Tambor de Mina: Lençol,
          Codó, Turquia, Bandeira, Gama, Bahia, Surrupira, entre outros.
        </p>

        <h2 class="text-h5 pa-4">Principais Ritos e Práticas</h2>

        <p class="pa-4">
          O Tambor de Mina é uma mistura de religiões do Daomé, Fon (jeje),
          Iorubá (nagô), Fante- Ashanti, Ketu, Agrono ou Cambinda
          (Angola-Congo), tradições indígenas americanas e europeias
          (catolicismo romano). Devido à riqueza cultural e ao sincretismo
          presentes no culto, esses elementos coexistem de forma harmoniosa. É
          comum a realização de festas e celebrações da cultura popular
          maranhense, como a Festa do Divino Espírito Santo, Bumba-meu-boi e
          Tambor de Crioula, que são por vezes solicitadas pelas entidades
          espirituais. O Terecô é uma derivação do Tambor de Mina, praticado em
          Codó e Teresina.
        </p>

        <h2 class="text-h5 pa-4">Maior Incidência nas Regiões do Brasil</h2>

        <p class="pa-4">
          O Tambor de Mina é praticado principalmente nos estados do Maranhão,
          Piauí, Pará e na floresta amazônica, com forte concentração em São
          Luís, Maranhão.
        </p>
      </div>

      <div id="umbanda">
        <h2 class="text-h4 pa-4">Umbanda</h2>

        <p class="pa-4">
          Umbanda é uma religião que surgiu no Brasil durante a década de 1920.
          Derivando em grande parte do Espiritismo, também combina elementos de
          tradições afro-brasileiras como o Candomblé, bem como do Catolicismo
          Romano. Não há uma autoridade central no controle da Umbanda, que é
          organizada em torno de locais de culto autônomos denominados centros
          ou terreiros, cujos seguidores são chamados de Umbandistas.
        </p>

        <h2 class="text-h5 pa-4">História no Brasil</h2>

        <p class="pa-4">
          O Catolicismo Romano era a religião dominante no Brasil no início do
          século XX, mas minorias consideráveis praticavam tradições
          afro-brasileiras ou Espiritismo, uma versão francesa do Espiritualismo
          desenvolvida por Allan Kardec. Por volta da década de 1920,vários
          grupos podem ter combinado práticas espíritas e afro-brasileiras,
          formando a base da Umbanda. O grupo mais importante foi o estabelecido
          por Zélio Fernandino de Moraes e seus colaboradores em Niterói, Rio de
          Janeiro. Ele havia se envolvido com o Espiritismo, mas desaprovava a
          atitude negativa que muitos espíritas tinham em relação ao contato com
          pretos velhos e caboclos. Refletindo o crescimento da Umbanda, em 1939
          de Moraes formou uma federação umbandista e em 1941 realizou o
          primeiro congresso umbandista. A Umbanda ganhou maior reconhecimento
          social e respeitabilidade durante a ditadura militar de 1964 a 1985,
          apesar da crescente oposição da Igreja Católica Romana e de grupos
          pentecostais. Desde a década de 1970, a Umbanda tem visto algum
          declínio devido à ressurgente popularidade do Candomblé.
        </p>

        <h2 class="text-h5 pa-4">Principais Entidades Cultuadas</h2>

        <p class="pa-4">
          Os adeptos desta religião monoteísta acreditam em um único Deus que
          está distante da humanidade. Abaixo desta entidade estão poderosos
          espíritos não-humanos chamados orixás. Na ala mais orientada para o
          Espiritismo da religião, a Umbanda Branca, estes são vistos como
          energias divinas ou forças da natureza; em formas mais africanizadas,
          são vistos como divindades da África Ocidental e são oferecidos
          sacrifícios de animais. Os emissários dos orixás são os pretos velhos
          e caboclos, espíritos de africanos escravizados e de indígenas
          brasileiros, respectivamente, e estas são as principais entidades
          tratadas pelos umbandistas. Em rituais umbandistas, médiuns cantam e
          dançam na esperança de serem possuídos por esses espíritos, através
          dos quais as congregações recebem orientação, conselhos e cura.
        </p>

        <h2 class="text-h5 pa-4">Principais Ritos e Práticas</h2>

        <p class="pa-4">
          A Umbanda ensina uma cosmologia complexa envolvendo um sistema de
          reencarnação de acordo com a lei do carma. A ética da religião
          enfatiza a caridade e a fraternidade social. Os umbandistas também
          procuram reverter os danos que atribuem aos praticantes de uma
          tradição relacionada, a Quimbanda. Os grupos umbandistas existem em um
          espectro, desde aqueles que enfatizam as conexões espíritas até
          aqueles que enfatizam os laços com o Candomblé e religiões
          afro-brasileiras relacionadas. Na prática, as religiões
          afro-brasileiras frequentemente se misturam, em vez de existirem em
          formas puras.
        </p>

        <h2 class="text-h5 pa-4">Maior Incidência nas Regiões do Brasil</h2>

        <p class="pa-4">
          Em seu auge nas décadas de 1960 e 1970, estimava-se que a Umbanda
          tinha entre 10 e 20 milhões de seguidores no Brasil. A Umbanda é
          encontrada principalmente em áreas urbanas do sul do Brasil, embora
          tenha se espalhado por todo o país e para outras partes das Américas.
        </p>
      </div>

