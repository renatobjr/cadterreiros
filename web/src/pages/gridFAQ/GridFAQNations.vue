      <div id="quimbanda">
        <h2 class="text-h4 pa-4">Quimbanda</h2>

        <p class="pa-4">
          Quimbanda, também grafada Kimbanda, é uma religião afro-brasileira
          praticada principalmente nos centros urbanos do Brasil. A Quimbanda
          foca em espíritos masculinos chamados Exus, bem como em suas
          contrapartes femininas, Pombagiras. As Pombagiras são frequentemente
          consideradas espíritos de mulheres falecidas que trabalharam como
          prostitutas ou em outras posições tradicionalmente consideradas
          imorais na sociedade católica brasileira. As práticas da Quimbanda são
          frequentemente focadas no sucesso mundano em relação a dinheiro e
          sexo. O termo Quimbanda veio da palavra Kimbundu kimbanda, que
          significa "curandeiro" ou "mago".
        </p>

        <h2 class="text-h5 pa-4">História no Brasil</h2>

        <p class="pa-4">
          A Quimbanda emergiu no Brasil, influenciada pelo Espiritismo
          Kardecista, catolicismo popular e religiões afro-brasileiras como o
          Candomblé. Historicamente, o termo Quimbanda tem sido usado por
          praticantes da Umbanda para caracterizar as práticas religiosas que
          eles se opunham, servindo como uma imagem espelhada para os
          umbandistas. As fronteiras entre Umbanda e Quimbanda não são sempre
          claras, com vários médiuns espirituais engajando ou promovendo
          práticas associadas a ambas.
        </p>

        <h2 class="text-h5 pa-4">Principais Entidades Cultuados</h2>

        <p class="pa-4">
          Na Quimbanda, os espíritos masculinos são conhecidos como Exus,
          considerados espíritos muito poderosos. Exus referem-se à falange de
          espíritos que lidam com questões humanas e materiais. As contrapartes
          femininas dos Exus são as Pombagiras, consideradas espíritos de
          mulheres imorais, associadas à sexualidade, sangue, morte e
          cemitérios. Elas são frequentemente apresentadas como atrevidas e
          sedutoras, falando em eufemismos sexuais. Ogum, o orixá da guerra e do
          metal, também é uma figura importante, atuando como uma figura
          intermediária entre os rituais de Exu na Quimbanda e os rituais da
          Umbanda.
        </p>

        <h2 class="text-h5 pa-4">Principais Ritos e Práticas</h2>

        <p class="pa-4">
          Um ritual de Quimbanda, chamado trabalho, consiste tipicamente em
          várias partes: um motivo, dedicação a um espírito, um local marginal,
          o material de metal ou argila (terroso), uma bebida alcoólica, perfume
          e comida (geralmente uma mistura de farinha de pimenta e azeite de
          dendê, às vezes chamada miamiami). O sacrifício animal, geralmente
          evitado na Umbanda, é comum na Quimbanda, assim como em muitas
          religiões afro-brasileiras. As espécies sacrificadas incluem pombos,
          galinhas, cabras, ovelhas e touros. As canções que os Quimbandistas
          cantam para as divindades são comumente chamadas de pontos.
        </p>

        <h2 class="text-h5 pa-4">Maior Incidência nas Regiões do Brasil</h2>

        <p class="pa-4">
          A Quimbanda é praticada principalmente nos centros urbanos do Brasil.
        </p>
